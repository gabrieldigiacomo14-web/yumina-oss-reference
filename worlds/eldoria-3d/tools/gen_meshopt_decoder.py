# Vendors meshoptimizer's glTF decoders (MIT) as src/meshopt-decoder.tsx: the WebAssembly decoder, with the library's own
# pure-JavaScript reference decoder as a fallback for hosts whose content security policy forbids WebAssembly.
#   python3 tools/gen_meshopt_decoder.py <node_modules/meshoptimizer>
import sys, os, re
d = sys.argv[1]
def body(f):
    s = open(os.path.join(d, f)).read(); s = re.sub(r"^export \{ MeshoptDecoder \};\s*$", "", s, flags=re.M); return s
lic = open(os.path.join(d, "LICENSE.md")).read().strip()
out = "// @ts-nocheck\n// GENERATED by tools/gen_meshopt_decoder.py from meshoptimizer (MIT licence, reproduced below). Do not edit.\n/*\n" + lic + "\n*/\n"
out += "function wasmDecoder() {\n" + body("meshopt_decoder.mjs") + "\nreturn MeshoptDecoder;\n}\n"
out += "function referenceDecoder() {\n" + body("meshopt_decoder_reference.js") + "\nreturn MeshoptDecoder;\n}\n"
out += """var DEC = null;
// One decoder for the GLTFLoader: WebAssembly when the host allows it, otherwise the reference decoder (slower, same output).
export function getMeshoptDecoder() {
  if (DEC) return DEC; var ref = referenceDecoder(); var w = null;
  try { if (typeof WebAssembly === "object" && !(typeof window !== "undefined" && window.__noWasm)) w = wasmDecoder(); } catch (e) { w = null; }
  DEC = { supported: true, impl: ref, kind: "reference" };
  DEC.ready = w ? Promise.race([w.ready.then(function () { DEC.impl = w; DEC.kind = "wasm"; }), new Promise(function (r) { setTimeout(r, 4000); })]).catch(function () { DEC.impl = ref; DEC.kind = "reference"; }) : Promise.resolve();
  DEC.decodeGltfBuffer = function (t, c, s, src, m, f) { return DEC.impl.decodeGltfBuffer(t, c, s, src, m, f); };
  DEC.decodeGltfBufferAsync = function (c, s, src, m, f) { return DEC.ready.then(function () { return DEC.impl.decodeGltfBufferAsync(c, s, src, m, f); }); };
  return DEC;
}
"""
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../src/meshopt-decoder.tsx"), "w").write(out)
print("wrote src/meshopt-decoder.tsx", len(out))
