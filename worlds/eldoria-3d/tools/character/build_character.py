    o = NB * (off * k)[:, None]
    if swell is not None: o = o + NB * swell(np.arange(len(Vm)))[:, None]
    ob, _ = make_mesh(name, faces, Vm, MORPHS if morph else None, offset=o); ob.data.materials.append(mat); return ob
