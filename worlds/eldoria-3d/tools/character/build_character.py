# Builds Eldoria's rigged humanoid GLB from CC0 MakeHuman assets with Blender's Python module.
#
#   python build_character.py --mh <makehuman/data> --template assets/models/eldoria-humanoid.glb --out assets/models/eldoria-human.glb
#
# What it does
#   body      hm08 base mesh shaped with MakeHuman's macro targets (young adult, athletic), helper geometry removed,
#             eyes fitted from the low-poly eye proxy, teeth and tongue kept for the open mouth.
#   morphs    female / build_* body morphs and facial expression units (blink, jaw, brows, smile, wince, pointed ears),
#             carried onto every clothing layer because clothing is cut from the body itself.
#   skeleton  MakeHuman's 163-bone default skeleton collapsed onto the game's 15 animated joints (+ feet); weights merged.
#   clips     every gameplay clip of the procedural template is retargeted with world-space rotation deltas and a
#             per-bone swing that maps this A-pose rest onto the template's rest, so timing and events stay identical.
#   sockets   socket_* empties reproduce the procedural hand/forearm/head frames, so weapons, shields and hoods fit.
#   outfits   outfit_light / _medium / _heavy / _robe / _bare layers cut from the body, hair_* and beard_* variants.
#   textures  generated by tex.py (no third-party images): skin with baked cavity shading, fabric, leather, mail, metal, hair.
