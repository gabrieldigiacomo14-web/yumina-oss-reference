def uv_density(faces):
    a3 = a2 = 0.0
    for f in faces:
        p = Vm[[c[0] for c in f]]; t = base.VT[[c[1] for c in f]]; a3 += np.linalg.norm(np.cross(p[1] - p[0], p[2] - p[0])); d1 = t[1] - t[0]; d2 = t[2] - t[0]; a2 += abs(d1[0] * d2[1] - d1[1] * d2[0])
    return math.sqrt(a2 / a3)
