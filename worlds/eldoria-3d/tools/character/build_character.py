def make_mesh(name, faces_sel, Vsrc, morphs=None, offset=None, uvs=True, weights=True, mats=None):
    """faces_sel: list of (corners) over base vertex indices. offset: per-base-vertex displacement (n,3, MakeHuman units)."""
    used = sorted({c[0] for f in faces_sel for c in f}); remap = {v: i for i, v in enumerate(used)}
    P = Vsrc[used] + (offset[used] if offset is not None else 0)
    me = bpy.data.meshes.new(name); verts = to_b(P).tolist(); polys = [[remap[c[0]] for c in f] for f in faces_sel]
    me.from_pydata(verts, [], polys); me.update()
    if uvs:
        uv = me.uv_layers.new(name="UVMap"); li = 0
        flat = [base.VT[c[1]] if c[1] >= 0 else (0, 0) for f in faces_sel for c in f]
        uv.data.foreach_set("uv", np.array(flat, dtype=np.float32).ravel())
    ob = bpy.data.objects.new(name, me); scene.collection.objects.link(ob)
    if weights:
        for g, arr in W.items():
            vg = ob.vertex_groups.new(name=g)
            for i, v in enumerate(used):
                if arr[v] > 0.001: vg.add([i], float(arr[v]), "REPLACE")
    if morphs:
        ob.shape_key_add(name="Basis", from_mix=False)
        for k, D in morphs.items():
            d = D[used]
            if np.abs(d).max() < 1e-5: continue
            sk = ob.shape_key_add(name=k, from_mix=False); sk.value = 0.0; co = (np.array(verts) + dvec(d)).astype(np.float32).ravel(); sk.data.foreach_set("co", co)
    for p in me.polygons: p.use_smooth = True
    return ob, used

