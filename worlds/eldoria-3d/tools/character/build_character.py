def vnormals(V, faces):
    N = np.zeros_like(V)
    for f in faces:
        idx = [c[0] for c in f]; p = V[idx]; n = np.cross(p[1] - p[0], p[2] - p[0]) + (np.cross(p[2] - p[0], p[3] - p[0]) if len(idx) == 4 else 0)
        N[idx] += n
    l = np.linalg.norm(N, axis=1); l[l == 0] = 1; return N / l[:, None]
