#!/usr/bin/env python3
"""Vendors three.js r149's GLTFLoader and SkeletonUtils.clone into src/gltf-loader.tsx.

The Yumina sandbox strips `import` statements and only has the UMD build of three.js as a global, so the
official ES-module loader is wrapped in a factory that receives THREE at runtime:
    var THREE = ...; var GLTFLoader = makeGLTFLoader(THREE); new GLTFLoader().parse(arrayBuffer, "", ok, fail)

Usage: python3 -I tools/gen_gltf_loader.py <path to node_modules/three>   (three@0.149.0, MIT licence)
"""
import re, sys, os
root = sys.argv[1]
J = os.path.join(root, "examples/jsm")
src = open(os.path.join(J, "loaders/GLTFLoader.js"), encoding="utf8").read()
m = re.match(r"import \{(.*?)\} from 'three';\s*import \{ toTrianglesDrawMode \} from '../utils/BufferGeometryUtils.js';", src, re.S)
assert m, "unexpected GLTFLoader header"
names = [n.strip() for n in m.group(1).split(",") if n.strip()]
for extra in ("TrianglesDrawMode",):  # used by toTrianglesDrawMode (BufferGeometryUtils imports it itself)
    if extra not in names: names.append(extra)
body = src[m.end():]
assert body.rstrip().endswith("export { GLTFLoader };")
body = body.rstrip()[: -len("export { GLTFLoader };")]
bgu = open(os.path.join(J, "utils/BufferGeometryUtils.js"), encoding="utf8").read()
a = bgu.index("function toTrianglesDrawMode")
# take the function through its closing brace (first line that is exactly "}")
b = bgu.index("\n}\n", a) + 3
tri = bgu[a:b]
su = open(os.path.join(J, "utils/SkeletonUtils.js"), encoding="utf8").read()
# clone() plus the helpers it needs
def grab(name):
    i = su.index("function " + name)
    j = su.index("\n}\n", i) + 3
    return su[i:j]
helpers = grab("clone") + "\n" + grab("parallelTraverse")
out = f"""// @ts-nocheck
// GENERATED by tools/gen_gltf_loader.py from three.js r149 (examples/jsm/loaders/GLTFLoader.js,
// utils/BufferGeometryUtils.js#toTrianglesDrawMode and utils/SkeletonUtils.js#clone). MIT licence, (c) three.js authors.
// Wrapped in a factory because the sandbox provides three.js as a runtime global instead of an importable module.
export function makeGLTFLoader(THREE) {{
const {{ {", ".join(names)} }} = THREE;
{tri}
{body}
return GLTFLoader;
}}
export function cloneSkinned(THREE, source) {{
const {{ Bone, Matrix4, Skeleton }} = THREE;
{helpers}
return clone(source);
}}
"""
open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src/gltf-loader.tsx"), "w", encoding="utf8").write(out)
print("wrote src/gltf-loader.tsx", len(out) // 1024, "KB;", len(names), "THREE symbols")
