"""Extract the original Eldoria sheet panels into src/panels.tsx.

The original rootComponent's sheet screens (Character with attribute spending,
Skills, Inventory/equip, Callings, Banking, Magic, Quest Boards, Party, Crafting,
Markets...) already implement the world's mechanics. They are reused verbatim so
the 3D edition keeps every rule; only the creator, adventure screen and app shell
are replaced. Run: python3 -I worlds/eldoria-3d/tools/gen_panels.py
"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
src = open(os.path.join(ROOT, "source", "original-index.tsx"), encoding="utf-8").read()
lines = src.split("\n")
def find(prefix):
    for i, l in enumerate(lines):
        if l.startswith(prefix): return i
    raise SystemExit("not found: " + prefix)
creator = find("function Creator("); adventure = find("function Adventure("); app = find("var SCREEN_META"); 
after_adv = adventure + 1
while not lines[after_adv].startswith("}"): after_adv += 1
after_adv += 1  # skip the closing brace of Adventure
body = lines[1:creator] + lines[after_adv:app]
css_a = src.index("var CSS=`"); css_b = src.index("`;", css_a)
css = src[css_a + 9:css_b]
names = sorted(set(re.findall(r"^function ([A-Za-z_]\w*)\(", "\n".join(body), re.M)))
consts = sorted(set(re.findall(r"^var ([A-Z_][A-Z0-9_]*)\s*[:=]", "\n".join(body), re.M)))
out = ["// @ts-nocheck", "// GENERATED by tools/gen_panels.py from the original Eldoria interface (source/original-index.tsx).", "// The sheet panels are kept verbatim so every original mechanic and normalizer contract is preserved.", ""]
out += body
open(os.path.join(ROOT, "src", "panels.tsx"), "w", encoding="utf-8").write("\n".join(out) + "\nexport var ORIGINAL_CSS = `" + css.replace("\\", "\\\\").replace("`", "\\`") + "`;\nexport { " + ", ".join(names + consts) + " };\n")
print("functions:", len(names), names)
print("consts:", consts)
