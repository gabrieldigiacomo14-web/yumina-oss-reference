import { chromium } from 'playwright-core';
const dir = new URL('.', import.meta.url).pathname;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
await p.goto('file://' + dir + 'out/index.html'); await p.waitForTimeout(600);
await p.evaluate(() => window.__KIT_EXTRA()); await p.waitForTimeout(200);
await p.locator('[aria-label="Satchel"], button:has-text("Satchel")').first().click(); await p.waitForTimeout(500);
const V = () => p.evaluate(() => window.__getVars());
const pl = (v, n) => JSON.stringify((v.inventory.find(i => i.name === n) || {}).placement);
const ok = (c, m) => console.log((c ? 'PASS ' : 'FAIL ') + m);
const open = async n => { await p.evaluate(n => [...document.querySelectorAll('.bck-row')].find(b => b.textContent.includes(n)).click(), n); await p.waitForTimeout(200); };
const btn = async t => { await p.evaluate(t => [...document.querySelectorAll('.bc-sheet-panel button')].find(b => b.textContent.startsWith(t)).click(), t); await p.waitForTimeout(400); };
await open('Short sword'); await btn('Equip');
let v = await V(); ok(pl(v,'Short sword') === '{"kind":"body","slot":"main-hand"}', 'sword equipped in the main hand: ' + pl(v,'Short sword'));
await open('Belt pouch'); await btn('Put on');
v = await V(); ok(/"kind":"body"/.test(pl(v,'Belt pouch')), 'belt pouch worn: ' + pl(v,'Belt pouch'));
await open('Healing potion'); await btn('Move to');
const reasons = await p.evaluate(() => [...document.querySelectorAll('.bck-move:not(.ok)')].map(b => b.textContent).slice(0, 3));
ok(reasons.length && reasons.every(r => /Won't fit/.test(r)), 'places that don\'t fit say why: ' + reasons[0]);
await p.evaluate(() => [...document.querySelectorAll('.bck-move.ok')].find(b => b.textContent.includes('Pocket 1')).click()); await p.waitForTimeout(400);
v = await V(); ok(/it-pouch/.test(pl(v,'Healing potion')), 'potions moved into the belt pouch: ' + pl(v,'Healing potion'));
await p.evaluate(() => [...document.querySelectorAll('.bck-here button')].find(b => b.textContent.includes('Take it')).click()); await p.waitForTimeout(400);
v = await V(); ok(!/"world"/.test(pl(v,'Rope')), 'rope taken from the ground: ' + pl(v,'Rope'));
await open('Rye loaf'); await btn('Split');
v = await V(); ok(v.inventory.filter(i => i.name === 'Rye loaf').length === 2, 'loaves split into two stacks');
await open('Torn travelling cloak');
ok(await p.evaluate(() => /mending/.test(document.querySelector('.bc-sheet-panel').textContent)), 'torn cloak flagged for mending');
await p.evaluate(() => document.querySelector('.bc-sheet-overlay').click()); await p.waitForTimeout(200);
await p.evaluate(() => window.__setVars({ in_combat: true })); await p.waitForTimeout(300);
await open('Farm knife');
const dis = await p.evaluate(() => { const b = [...document.querySelectorAll('.bc-sheet-panel button')].find(b => b.textContent.startsWith('Use (free)')); return b ? b.disabled : null; });
const warn = await p.evaluate(() => /In a fight this is buried/.test(document.querySelector('.bc-sheet-panel').textContent));
ok(dis === true && warn, 'buried knife can\'t be used in a fight');
const ev = (await V()).equipment_activity || [];
ok(ev.length >= 3, 'each change was logged for the narrator (' + ev.length + ' recent events)');
console.log(errs.length ? 'ERRORS ' + errs.join('\n') : 'no page errors');
await b.close();
