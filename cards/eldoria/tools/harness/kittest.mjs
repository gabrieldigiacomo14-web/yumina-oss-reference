import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)('playwright');
const dir = new URL('.', import.meta.url).pathname;
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 390, height: 844 } });
const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
await p.goto('file://' + dir + 'out/index.html'); await p.waitForTimeout(400);
const V = () => p.evaluate(() => window.__getVars());
const it = (v, n) => v.inventory.find(i => i.name === n);
const ok = (c, m) => console.log((c ? 'PASS ' : 'FAIL ') + m);
const open = async n => { await p.evaluate(n => { const t = [...document.querySelectorAll('.itemTile')].find(b => b.textContent.includes(n)); t.click(); }, n); await p.waitForTimeout(150); };
const btn = async t => { await p.evaluate(t => [...document.querySelectorAll('.sheet button')].find(b => b.textContent.startsWith(t)).click(), t); await p.waitForTimeout(200); };
await p.locator('.navBtn', { hasText: 'Gear' }).first().click(); await p.waitForTimeout(400);
let v = await V();
ok(v.inventory.every(i => i.placement), 'every item was given a place');
ok(it(v,'Broadhead Arrows').placement.slotId === 'arrows', 'arrows went into the quiver');
await open('Dented Iron Helm'); await btn('Equip');
v = await V(); ok(v.equipment.head === 'old-helm' && it(v,'Dented Iron Helm').equipped && it(v,'Dented Iron Helm').placement.kind === 'body', 'helm equipped into the head slot');
await open('Belt Pouch'); await btn('Put on');
v = await V(); ok(it(v,'Belt Pouch').placement.kind === 'body', 'belt pouch worn');
await open('Healing Draught'); await btn('Move to');
await p.evaluate(() => [...document.querySelectorAll('.ekMove.ok')].find(b => b.textContent.includes('Belt Pouch')).click()); await p.waitForTimeout(200);
v = await V(); ok(it(v,'Healing Draught').placement.containerId === 'pouch', 'draught moved into the belt pouch');
await open('Broadhead Arrows'); await btn('Split');
v = await V(); ok(v.inventory.filter(i => i.name === 'Broadhead Arrows').map(i => i.qty).sort((a,b)=>a-b).join() === '12,12', 'arrows split 12 + 12');
await p.evaluate(() => document.querySelector('.sheetVeil') && document.querySelector('.sheetVeil').click()); await p.waitForTimeout(100);
await p.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Pick up').click()); await p.waitForTimeout(200);
v = await V(); ok(v['ground-items'].length === 0 && it(v,'Hooded Lantern'), 'lantern picked up into ' + JSON.stringify(it(v,'Hooded Lantern').placement));
await open('Hemp Rope'); await btn('Drop');
v = await V(); ok(!it(v,'Hemp Rope') && v['ground-items'][0].name === 'Hemp Rope', 'rope dropped on the ground');
await open('Yew Longbow'); await btn('Take off');
v = await V(); ok(v.equipment.weapon === null && !it(v,'Yew Longbow').equipped, 'bow taken off, now ' + JSON.stringify(it(v,'Yew Longbow').placement));
await p.evaluate(() => window.__setVars({ 'in-combat': true })); await p.waitForTimeout(250);
await open('Trail Rations'); await btn('Use');
const sent = await p.evaluate(() => (window.__sent || []).join('|'));
ok(!/Trail Rations/.test(sent), 'buried rations refused in a fight');
await open('Healing Draught'); await btn('Use');
ok(/Healing Draught \(quick\)/.test(await p.evaluate(() => (window.__sent || []).join('|'))), 'draught from the belt pouch usable in a fight');
ok((await p.evaluate(() => (window.__ctx || []).length)) >= 7, 'the narrator was told about each physical change');
console.log(errs.length ? 'ERRORS ' + errs.join('\n') : 'no page errors');
await b.close();
